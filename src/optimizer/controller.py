"""
BytePi4 Optimization Controller

Coordinates:

    Profiler Metrics
          |
          v
    ResourceManager
          |
          v
      System State
          |
          +-------------------+
          |                   |
          v                   v
    Adaptive Skip       Dynamic Resolution
          |                   |
          +---------+---------+
                    |
                    v
            OptimizationDecision

The controller decides WHAT optimization policy should be applied.
It does not capture camera frames or run YOLO inference.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any, Dict, Optional, Tuple

from src.optimizer.resource_manager import (
    ResourceManager,
    ResourceEvaluation,
    SystemState,
)
from src.optimizer.adaptive_skip import AdaptiveFrameSkip
from src.optimizer.dynamic_resolution import DynamicResolution


logger = logging.getLogger("BytePi4OptimizationController")


# ==========================================================
# OPTIMIZATION DECISION
# ==========================================================

@dataclass
class OptimizationDecision:
    """
    Complete optimization decision generated by the controller.
    """

    state: str
    action: str

    frame_skip: int
    resolution: Tuple[int, int]

    cpu: float
    memory: float
    temperature: Optional[float]

    fps: float
    latency_ms: float

    reason: str

    thermal_state: str

    def to_dict(self) -> Dict[str, Any]:
        """
        Convert decision into a JSON/dashboard-friendly dictionary.
        """

        return {
            "state": self.state,
            "action": self.action,

            "frame_skip": self.frame_skip,

            "resolution": list(self.resolution),

            "cpu": self.cpu,
            "memory": self.memory,
            "temperature": self.temperature,

            "fps": self.fps,
            "latency_ms": self.latency_ms,

            "reason": self.reason,

            "thermal_state": self.thermal_state,
        }


# ==========================================================
# CONTROLLER
# ==========================================================

class OptimizationController:
    """
    Central BytePi4 optimization decision engine.

    Responsibilities:

        1. Evaluate system resources.
        2. Determine system state.
        3. Update adaptive frame skipping.
        4. Update dynamic resolution.
        5. Generate an explainable optimization decision.

    It does NOT:

        - capture camera frames
        - resize frames directly
        - execute YOLO inference
        - control the camera
    """

    def __init__(
        self,
        resource_manager: Optional[ResourceManager] = None,
        adaptive_skip: Optional[AdaptiveFrameSkip] = None,
        dynamic_resolution: Optional[DynamicResolution] = None,
    ):
        """
        Initialize the optimization controller.
        """

        # ------------------------------------------------------
        # Resource manager
        # ------------------------------------------------------

        self.resource_manager = (
            resource_manager
            or ResourceManager()
        )

        # ------------------------------------------------------
        # Adaptive frame skipping
        # ------------------------------------------------------

        self.adaptive_skip = (
            adaptive_skip
            or AdaptiveFrameSkip()
        )

        # ------------------------------------------------------
        # Dynamic resolution
        # ------------------------------------------------------

        self.dynamic_resolution = (
            dynamic_resolution
            or DynamicResolution()
        )

        # ------------------------------------------------------
        # State
        # ------------------------------------------------------

        self.evaluation_count = 0

        self.last_evaluation: Optional[
            ResourceEvaluation
        ] = None

        self.last_decision: Optional[
            OptimizationDecision
        ] = None

        logger.info(
            "BytePi4 Optimization Controller initialized"
        )

    # ==========================================================
    # EVALUATE
    # ==========================================================

    def evaluate(
        self,
        metrics: Optional[Dict[str, Any]] = None,
        **kwargs,
    ) -> OptimizationDecision:
        """
        Evaluate current metrics and generate an optimization decision.

        Parameters
        ----------
        metrics:
            Metrics generated by Profiler.

        Expected keys:

            cpu
            memory
            temperature
            fps
            inference_ms

        Returns
        -------
        OptimizationDecision
        """

        if metrics is None:
            metrics = {}

        # ------------------------------------------------------
        # Merge keyword metrics
        # ------------------------------------------------------

        combined_metrics = dict(metrics)

        combined_metrics.update(kwargs)

        # ------------------------------------------------------
        # Resource evaluation
        # ------------------------------------------------------

        evaluation = (
            self.resource_manager.evaluate(
                combined_metrics
            )
        )

        self.last_evaluation = evaluation

        self.evaluation_count += 1

        # ------------------------------------------------------
        # Extract metrics
        # ------------------------------------------------------

        state = evaluation.state

        fps = evaluation.fps

        latency_ms = evaluation.latency_ms

        # ------------------------------------------------------
        # Update adaptive frame skip
        # ------------------------------------------------------

        frame_skip = (
            self.adaptive_skip.update(
                system_state=state,
                fps=fps,
                latency=latency_ms,
                metrics=combined_metrics,
            )
        )

        # ------------------------------------------------------
        # Update dynamic resolution
        # ------------------------------------------------------

        resolution = (
            self.dynamic_resolution.update(
                system_state=state,
                fps=fps,
                latency=latency_ms,
            )
        )

        # ------------------------------------------------------
        # Determine action
        # ------------------------------------------------------

        action = self._determine_action(
            state=state,
            frame_skip=frame_skip,
            resolution=resolution,
        )

        # ------------------------------------------------------
        # Thermal state
        # ------------------------------------------------------

        thermal_state = evaluation.thermal_state

        # ------------------------------------------------------
        # Create decision
        # ------------------------------------------------------

        decision = OptimizationDecision(
            state=(
                state.value
                if isinstance(state, SystemState)
                else str(state)
            ),

            action=action,

            frame_skip=frame_skip,

            resolution=resolution,

            cpu=evaluation.cpu,

            memory=evaluation.memory,

            temperature=evaluation.temperature,

            fps=fps,

            latency_ms=latency_ms,

            reason=evaluation.reason,

            thermal_state=(
                thermal_state.value
                if hasattr(
                    thermal_state,
                    "value",
                )
                else str(thermal_state)
            ),
        )

        self.last_decision = decision

        logger.info(
            "Optimization decision | "
            "state=%s | "
            "action=%s | "
            "skip=%d | "
            "resolution=%s",
            decision.state,
            decision.action,
            decision.frame_skip,
            decision.resolution,
        )

        return decision

    # ==========================================================
    # ACTION
    # ==========================================================

    def _determine_action(
        self,
        state: SystemState,
        frame_skip: int,
        resolution: Tuple[int, int],
    ) -> str:
        """
        Generate a human-readable optimization action.

        This is intentionally explainable for the dashboard
        and demonstration.
        """

        if state == SystemState.CRITICAL:

            return (
                "CRITICAL_LOAD: "
                "maximum frame skipping and "
                "lowest available resolution"
            )

        if state == SystemState.HIGH_LOAD:

            return (
                "HIGH_LOAD: "
                "reduce inference frequency and "
                "lower workload resolution"
            )

        if state == SystemState.LOW_LOAD:

            if (
                frame_skip == 0
                and resolution
                == self.dynamic_resolution.levels[0]
            ):

                return (
                    "LOW_LOAD: "
                    "full inference rate and "
                    "maximum resolution"
                )

            return (
                "LOW_LOAD: "
                "recover toward maximum performance"
            )

        # NORMAL

        return (
            "NORMAL: "
            "maintain current workload policy"
        )

    # ==========================================================
    # STATE
    # ==========================================================

    def get_state(self) -> SystemState:
        """
        Return current normalized system state.
        """

        return self.resource_manager.get_state()

    # ==========================================================
    # LATEST EVALUATION
    # ==========================================================

    def get_latest_evaluation(
        self,
    ) -> Optional[ResourceEvaluation]:

        return self.last_evaluation

    # ==========================================================
    # LATEST DECISION
    # ==========================================================

    def get_latest_decision(
        self,
    ) -> Optional[OptimizationDecision]:

        return self.last_decision

    # ==========================================================
    # CURRENT FRAME SKIP
    # ==========================================================

    def get_frame_skip(self) -> int:
        """
        Return current adaptive frame skip level.
        """

        return self.adaptive_skip.get_skip()

    # ==========================================================
    # CURRENT RESOLUTION
    # ==========================================================

    def get_resolution(
        self,
    ) -> Tuple[int, int]:
        """
        Return current target resolution.
        """

        return self.dynamic_resolution.get_resolution()

    # ==========================================================
    # STATUS
    # ==========================================================

    def get_status(self) -> Dict[str, Any]:
        """
        Return controller state for monitoring/Grafana/debugging.
        """

        decision = self.last_decision

        evaluation = self.last_evaluation

        return {
            "evaluation_count":
                self.evaluation_count,

            "state":
                (
                    decision.state
                    if decision
                    else self.get_state().value
                ),

            "frame_skip":
                self.get_frame_skip(),

            "resolution":
                list(
                    self.get_resolution()
                ),

            "action":
                (
                    decision.action
                    if decision
                    else None
                ),

            "reason":
                (
                    decision.reason
                    if decision
                    else None
                ),

            "cpu":
                (
                    evaluation.cpu
                    if evaluation
                    else None
                ),

            "memory":
                (
                    evaluation.memory
                    if evaluation
                    else None
                ),

            "temperature":
                (
                    evaluation.temperature
                    if evaluation
                    else None
                ),

            "fps":
                (
                    evaluation.fps
                    if evaluation
                    else None
                ),

            "latency_ms":
                (
                    evaluation.latency_ms
                    if evaluation
                    else None
                ),

            "thermal_state":
                (
                    evaluation.thermal_state.value
                    if evaluation
                    and hasattr(
                        evaluation.thermal_state,
                        "value",
                    )
                    else None
                ),
        }

    # ==========================================================
    # RESET
    # ==========================================================

    def reset(self) -> None:
        """
        Reset optimization state.
        """

        self.evaluation_count = 0

        self.last_evaluation = None

        self.last_decision = None

        # ------------------------------------------------------
        # Reset frame skip
        # ------------------------------------------------------

        self.adaptive_skip.current_skip = (
            self.adaptive_skip.min_skip
        )

        self.adaptive_skip._hold_counter = 0

        self.adaptive_skip.reset_frame_counter()

        # ------------------------------------------------------
        # Reset dynamic resolution
        # ------------------------------------------------------

        self.dynamic_resolution.current_level = max(
            0,
            min(
                int(
                    self.dynamic_resolution.config.get(
                        "default_level",
                        0,
                    )
                ),
                self.dynamic_resolution.max_level_index,
            ),
        )

        self.dynamic_resolution._hold_counter = 0

        # ------------------------------------------------------
        # Reset resource manager
        # ------------------------------------------------------

        self.resource_manager.current_state = (
            SystemState.NORMAL
        )

        self.resource_manager._latest_evaluation = None

        self.resource_manager._candidate_state = None

        self.resource_manager._candidate_count = 0

        logger.info(
            "BytePi4 Optimization Controller reset"
        )

    # ==========================================================
    # REPRESENTATION
    # ==========================================================

    def __repr__(self) -> str:

        return (
            "OptimizationController("
            f"state='{self.get_state().value}', "
            f"frame_skip={self.get_frame_skip()}, "
            f"resolution={self.get_resolution()}"
            ")"
        )